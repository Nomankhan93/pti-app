create or replace function app_private.consume_rate_limit(
  p_action text,
  p_limit integer,
  p_window_seconds integer
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  clean_action text := lower(trim(coalesce(p_action,'')));
  now_value timestamptz := clock_timestamp();
  window_start timestamptz;
  bucket text;
  hits integer;
begin
  if actor is null then raise exception 'Authentication required'; end if;
  if length(clean_action) not between 2 and 80 then raise exception 'Invalid rate-limit action'; end if;
  if p_limit is null or p_limit < 1 or p_limit > 10000 then raise exception 'Invalid rate-limit threshold'; end if;
  if p_window_seconds is null or p_window_seconds < 10 or p_window_seconds > 86400 then raise exception 'Invalid rate-limit window'; end if;

  window_start := to_timestamp((
    floor(extract(epoch from now_value) / p_window_seconds) * p_window_seconds
  )::double precision);
  bucket := actor::text || ':' || clean_action || ':' || extract(epoch from window_start)::bigint::text;

  insert into app_private.rate_limit_buckets(
    bucket_key, actor_id, action, window_started_at, window_seconds, hit_count, updated_at
  )
  values(bucket, actor, clean_action, window_start, p_window_seconds, 1, now_value)
  on conflict (bucket_key) do update
    set hit_count = app_private.rate_limit_buckets.hit_count + 1,
        updated_at = excluded.updated_at
  returning hit_count into hits;

  if hits > p_limit then
    raise exception 'Rate limit exceeded for %; retry after the current window', clean_action
      using errcode = 'P0001';
  end if;

  -- Opportunistic cleanup. This never needs to be exact; old buckets are not used.
  delete from app_private.rate_limit_buckets
  where updated_at < now_value - interval '2 days';

  return greatest(p_limit - hits, 0);
end;
$$;

revoke all on function app_private.can_manage_production(uuid) from public, anon, authenticated;
