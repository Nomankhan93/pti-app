create or replace function app_private.production_health_summary_impl()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  rls_missing integer := 0;
  direct_write_exposure integer := 0;
  negative_finance integer := 0;
  stale_finance integer := 0;
  unmapped_members integer := 0;
  critical_unread integer := 0;
  legacy_public_definers integer := 0;
  recent_exports integer := 0;
  active_rate_buckets integer := 0;
  overall text;
begin
  if actor is null or not app_private.can_manage_production(actor) then
    raise exception 'Production readiness access required';
  end if;

  select count(*)::integer into rls_missing
  from (
    values
      ('audit_events'),
      ('organization_role_assignments'),
      ('finance_role_assignments'),
      ('fundraising_campaigns'),
      ('donations'),
      ('donation_verification_events'),
      ('donation_reconciliation_events'),
      ('donation_adjustments'),
      ('donation_receipts'),
      ('notification_messages'),
      ('notification_deliveries'),
      ('production_export_audit')
  ) as expected(table_name)
  left join (
    select c.relname, c.relrowsecurity
    from pg_catalog.pg_class c
    join pg_catalog.pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
  ) c on c.relname = expected.table_name
  where c.relname is null or not c.relrowsecurity;

  select count(*)::integer into direct_write_exposure
  from (
    values
      ('public.audit_events'),
      ('public.organization_role_assignments'),
      ('public.finance_role_assignments'),
      ('public.donations'),
      ('public.donation_verification_events'),
      ('public.donation_reconciliation_events'),
      ('public.donation_adjustments'),
      ('public.donation_receipts'),
      ('public.notification_messages'),
      ('public.notification_deliveries'),
      ('public.production_export_audit')
  ) as expected(table_name)
  where
    pg_catalog.has_table_privilege('anon', expected.table_name, 'INSERT')
    or pg_catalog.has_table_privilege('anon', expected.table_name, 'UPDATE')
    or pg_catalog.has_table_privilege('anon', expected.table_name, 'DELETE')
    or pg_catalog.has_table_privilege('authenticated', expected.table_name, 'INSERT')
    or pg_catalog.has_table_privilege('authenticated', expected.table_name, 'UPDATE')
    or pg_catalog.has_table_privilege('authenticated', expected.table_name, 'DELETE');

  select count(*)::integer into negative_finance
  from public.donations d
  where d.amount + coalesce((
    select sum(a.amount_delta) from public.donation_adjustments a where a.donation_id = d.id
  ),0) < 0;

  select count(*)::integer into stale_finance
  from public.donations d
  where d.received_at < now() - interval '7 days'
    and app_private.latest_donation_verification_state(d.id) = 'pending'::public.donation_verification_state;

  select count(*)::integer into unmapped_members
  from public.members m
  where m.is_active and m.org_unit_id is null;

  select count(*)::integer into critical_unread
  from public.notification_deliveries d
  join public.notification_messages m on m.id = d.message_id
  where d.read_at is null
    and d.archived_at is null
    and m.status = 'published'::public.notification_status
    and m.severity = 'critical'::public.notification_severity
    and (m.expires_at is null or m.expires_at > now());

  select count(*)::integer into legacy_public_definers
  from pg_catalog.pg_proc p
  join pg_catalog.pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prosecdef
    and pg_catalog.has_function_privilege('authenticated', p.oid, 'EXECUTE');

  select count(*)::integer into recent_exports
  from public.production_export_audit
  where created_at >= now() - interval '24 hours';

  select count(*)::integer into active_rate_buckets
  from app_private.rate_limit_buckets
  where updated_at >= now() - interval '15 minutes';

  overall := case
    when rls_missing > 0 or direct_write_exposure > 0 or negative_finance > 0 then 'fail'
    when stale_finance > 0 or unmapped_members > 0 or legacy_public_definers > 0 then 'warn'
    else 'ok'
  end;

  return jsonb_build_object(
    'status', overall,
    'database_time', now(),
    'checks', jsonb_build_object(
      'rls_missing', rls_missing,
      'direct_write_exposure', direct_write_exposure,
      'negative_finance_ledger', negative_finance,
      'stale_pending_finance', stale_finance,
      'unmapped_active_members', unmapped_members,
      'critical_unread_deliveries', critical_unread,
      'legacy_public_security_definer_rpcs', legacy_public_definers,
      'exports_last_24h', recent_exports,
      'active_rate_limit_buckets', active_rate_buckets
    )
  );
end;
$$;

create or replace function app_private.production_export_audit_events_impl(
  p_org_unit_id uuid default null,
  p_from timestamptz default null,
  p_to timestamptz default null,
  p_limit integer default 1000
)
returns table(
  event_id bigint,
  actor_id uuid,
  action text,
  entity_type text,
  entity_id uuid,
  org_unit_id uuid,
  org_unit_name text,
  detail jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  safe_limit integer := greatest(1, least(coalesce(p_limit,1000),5000));
  exported integer := 0;
  export_id bigint;
begin
  if actor is null or not app_private.can_manage_production(actor) then
    raise exception 'Production export access required';
  end if;
  if p_from is not null and p_to is not null and p_to < p_from then
    raise exception 'Invalid export date range';
  end if;
  if p_org_unit_id is not null and not app_private.can_access_org_unit(actor,p_org_unit_id) then
    raise exception 'Organization scope access required';
  end if;
  perform app_private.consume_rate_limit('production_export_audit',10,300);

  return query
  select
    a.id,
    a.actor_id,
    a.action,
    a.entity_type,
    a.entity_id,
    a.org_unit_id,
    ou.name,
    a.detail,
    a.created_at
  from public.audit_events a
  left join public.organization_units ou on ou.id = a.org_unit_id
  where (p_from is null or a.created_at >= p_from)
    and (p_to is null or a.created_at <= p_to)
    and (
      p_org_unit_id is null
      or a.org_unit_id is null
      or exists (
        select 1
        from public.organization_unit_closure c
        where c.ancestor_id = p_org_unit_id
          and c.descendant_id = a.org_unit_id
      )
    )
  order by a.created_at desc, a.id desc
  limit safe_limit;

  get diagnostics exported = row_count;
  insert into public.production_export_audit(actor_id,export_kind,org_unit_id,row_count,filters)
  values(actor,'audit_events',p_org_unit_id,exported,jsonb_build_object('from',p_from,'to',p_to,'limit',safe_limit))
  returning id into export_id;

  insert into public.audit_events(actor_id,action,entity_type,entity_id,org_unit_id,detail)
  values(actor,'production_export_created','production_export',null,p_org_unit_id,
    jsonb_build_object('export_id',export_id,'export_kind','audit_events','row_count',exported));
end;
$$;

create or replace function app_private.production_export_finance_ledger_impl(
  p_org_unit_id uuid default null,
  p_from timestamptz default null,
  p_to timestamptz default null,
  p_limit integer default 1000
)
returns table(
  donation_no text,
  campaign_no text,
  campaign_title text,
  org_unit_id uuid,
  org_unit_name text,
  base_amount numeric,
  adjustment_total numeric,
  effective_amount numeric,
  currency text,
  payment_method public.finance_payment_method,
  received_at timestamptz,
  verification_state public.donation_verification_state,
  reconciliation_state public.donation_reconciliation_state,
  latest_receipt_no text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  safe_limit integer := greatest(1, least(coalesce(p_limit,1000),5000));
  exported integer := 0;
  export_id bigint;
begin
  if actor is null or not app_private.can_manage_production(actor) then
    raise exception 'Production finance export access required';
  end if;
  if p_from is not null and p_to is not null and p_to < p_from then
    raise exception 'Invalid export date range';
  end if;
  if p_org_unit_id is not null and not app_private.can_view_finance(actor,p_org_unit_id) then
    raise exception 'Finance scope access required';
  end if;
  perform app_private.consume_rate_limit('production_export_finance',10,300);

  return query
  select
    d.donation_no,
    c.campaign_no,
    c.title,
    d.org_unit_id,
    ou.name,
    d.amount,
    coalesce((select sum(a.amount_delta) from public.donation_adjustments a where a.donation_id=d.id),0),
    app_private.effective_donation_amount(d.id),
    d.currency,
    d.payment_method,
    d.received_at,
    app_private.latest_donation_verification_state(d.id),
    app_private.latest_donation_reconciliation_state(d.id),
    (select r.receipt_no from public.donation_receipts r where r.donation_id=d.id order by r.version desc limit 1),
    d.created_at
  from public.donations d
  left join public.fundraising_campaigns c on c.id = d.campaign_id
  join public.organization_units ou on ou.id = d.org_unit_id
  where (p_from is null or d.received_at >= p_from)
    and (p_to is null or d.received_at <= p_to)
    and (
      p_org_unit_id is null
      or exists (
        select 1
        from public.organization_unit_closure scope_tree
        where scope_tree.ancestor_id = p_org_unit_id
          and scope_tree.descendant_id = d.org_unit_id
      )
    )
  order by d.received_at desc, d.created_at desc
  limit safe_limit;

  get diagnostics exported = row_count;
  insert into public.production_export_audit(actor_id,export_kind,org_unit_id,row_count,filters)
  values(actor,'finance_ledger',p_org_unit_id,exported,jsonb_build_object('from',p_from,'to',p_to,'limit',safe_limit,'pii','excluded'))
  returning id into export_id;

  insert into public.audit_events(actor_id,action,entity_type,entity_id,org_unit_id,detail)
  values(actor,'production_export_created','production_export',null,p_org_unit_id,
    jsonb_build_object('export_id',export_id,'export_kind','finance_ledger','row_count',exported,'pii','excluded'));
end;
$$;

