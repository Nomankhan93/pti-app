create table app_private.rate_limit_buckets (
  bucket_key text primary key,
  actor_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  window_started_at timestamptz not null,
  window_seconds integer not null,
  hit_count integer not null default 1,
  updated_at timestamptz not null default now(),
  constraint rate_limit_action_check check (length(action) between 2 and 80),
  constraint rate_limit_window_check check (window_seconds between 10 and 86400),
  constraint rate_limit_hit_count_check check (hit_count > 0)
);

create index rate_limit_buckets_actor_idx
  on app_private.rate_limit_buckets(actor_id, updated_at desc);
create index rate_limit_buckets_updated_idx
  on app_private.rate_limit_buckets(updated_at);

create table public.production_export_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users(id) on delete restrict,
  export_kind text not null,
  org_unit_id uuid references public.organization_units(id) on delete restrict,
  row_count integer not null,
  filters jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint production_export_kind_check check (export_kind in ('audit_events','finance_ledger')),
  constraint production_export_row_count_check check (row_count >= 0),
  constraint production_export_filters_check check (jsonb_typeof(filters) = 'object')
);

create index production_export_audit_created_idx
  on public.production_export_audit(created_at desc);
create index production_export_audit_actor_idx
  on public.production_export_audit(actor_id, created_at desc);
create index production_export_audit_scope_idx
  on public.production_export_audit(org_unit_id, created_at desc);

alter table public.production_export_audit enable row level security;
revoke all on public.production_export_audit from public, anon, authenticated;
revoke all on app_private.rate_limit_buckets from public, anon, authenticated;

