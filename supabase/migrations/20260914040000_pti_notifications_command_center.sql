create or replace function app_private.notification_recipient_ids(
  p_audience public.notification_audience,
  p_org_unit_id uuid,
  p_operation_id uuid,
  p_target_spec jsonb
)
returns table(user_id uuid)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_org_unit_id is null then
    raise exception 'Notification scope is required';
  end if;

  if p_audience = 'org_scope'::public.notification_audience then
    return query
    select distinct recipients.user_id
    from (
      select m.user_id
      from public.members m
      where m.is_active
        and m.org_unit_id is not null
        and app_private.is_org_descendant(m.org_unit_id, p_org_unit_id)

      union

      select vp.user_id
      from public.volunteer_profiles vp
      where vp.is_active
        and app_private.is_org_descendant(vp.org_unit_id, p_org_unit_id)

      union

      select ra.user_id
      from public.organization_role_assignments ra
      where ra.is_active
        and app_private.is_org_descendant(ra.org_unit_id, p_org_unit_id)

      union

      select fra.user_id
      from public.finance_role_assignments fra
      where fra.is_active
        and app_private.is_org_descendant(fra.org_unit_id, p_org_unit_id)
    ) recipients;
    return;
  end if;

  if p_audience = 'members'::public.notification_audience then
    return query
    select distinct m.user_id
    from public.members m
    where m.is_active
      and m.org_unit_id is not null
      and app_private.is_org_descendant(m.org_unit_id, p_org_unit_id);
    return;
  end if;

  if p_audience = 'volunteers'::public.notification_audience then
    return query
    select distinct vp.user_id
    from public.volunteer_profiles vp
    where vp.is_active
      and app_private.is_org_descendant(vp.org_unit_id, p_org_unit_id);
    return;
  end if;

  if p_audience = 'organization_roles'::public.notification_audience then
    return query
    select distinct ra.user_id
    from public.organization_role_assignments ra
    where ra.is_active
      and app_private.is_org_descendant(ra.org_unit_id, p_org_unit_id)
      and ra.role = any (
        coalesce(
          array(
            select value::public.organization_role
            from jsonb_array_elements_text(coalesce(p_target_spec->'organization_roles', '[]'::jsonb)) as value
          ),
          '{}'::public.organization_role[]
        )
      );
    return;
  end if;

  if p_audience = 'finance_roles'::public.notification_audience then
    return query
    select distinct fra.user_id
    from public.finance_role_assignments fra
    where fra.is_active
      and app_private.is_org_descendant(fra.org_unit_id, p_org_unit_id)
      and fra.role = any (
        coalesce(
          array(
            select value::public.finance_role
            from jsonb_array_elements_text(coalesce(p_target_spec->'finance_roles', '[]'::jsonb)) as value
          ),
          '{}'::public.finance_role[]
        )
      );
    return;
  end if;

  if p_audience = 'operation_participants'::public.notification_audience then
    if p_operation_id is null then
      raise exception 'Operation participant notifications require an operation';
    end if;

    return query
    select distinct recipients.user_id
    from (
      select oc.user_id
      from public.operation_coordinators oc
      where oc.operation_id = p_operation_id and oc.is_active

      union

      select vp.user_id
      from public.operation_team_members otm
      join public.operation_teams ot on ot.id = otm.team_id
      join public.volunteer_profiles vp on vp.id = otm.volunteer_id
      where ot.operation_id = p_operation_id
        and otm.is_active
        and vp.is_active

      union

      select vp.user_id
      from public.duty_assignments da
      join public.operation_duties od on od.id = da.duty_id
      join public.volunteer_profiles vp on vp.id = da.volunteer_id
      where od.operation_id = p_operation_id
        and da.status <> 'cancelled'::public.duty_status
        and vp.is_active
    ) recipients;
    return;
  end if;

  if p_audience = 'specific_users'::public.notification_audience then
    return query
    select distinct selected.user_id
    from (
      select value::uuid as user_id
      from jsonb_array_elements_text(coalesce(p_target_spec->'user_ids', '[]'::jsonb)) as value
    ) selected
    where app_private.user_in_notification_scope(selected.user_id, p_org_unit_id);
    return;
  end if;

  raise exception 'Unsupported notification audience';
end;
$$;

revoke all on function app_private.notification_recipient_ids(public.notification_audience,uuid,uuid,jsonb) from public, anon, authenticated;

