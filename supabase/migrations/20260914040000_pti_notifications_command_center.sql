create or replace function app_private.notify_duty_assignment_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  duty_row public.operation_duties;
  operation_row public.operations;
  volunteer_row public.volunteer_profiles;
  start_at timestamptz;
  start_text text;
  location_text text;
  source text;
begin
  if new.status <> 'assigned'::public.duty_status then
    return new;
  end if;

  if tg_op = 'UPDATE'
     and old.status = new.status
     and old.assigned_at is not distinct from new.assigned_at then
    return new;
  end if;

  select * into duty_row from public.operation_duties where id = new.duty_id;
  select * into operation_row from public.operations where id = duty_row.operation_id;
  select * into volunteer_row from public.volunteer_profiles where id = new.volunteer_id;

  if duty_row.id is null or operation_row.id is null or volunteer_row.user_id is null then
    return new;
  end if;

  select coalesce(duty_row.starts_at, s.starts_at, operation_row.starts_at)
    into start_at
  from public.operation_duties d
  left join public.operation_shifts s on s.id = duty_row.shift_id
  where d.id = duty_row.id;

  start_text := case when start_at is null then 'Time to be confirmed' else to_char(start_at, 'DD Mon YYYY HH24:MI TZ') end;
  location_text := coalesce(nullif(trim(duty_row.location), ''), nullif(trim(operation_row.location), ''), 'Location to be confirmed');
  source := 'duty-assigned:' || new.id::text || ':' || floor(extract(epoch from new.assigned_at))::bigint::text;

  perform app_private.publish_direct_notification_to_user(
    volunteer_row.user_id,
    duty_row.org_unit_id,
    duty_row.operation_id,
    'duty_reminder'::public.notification_kind,
    case duty_row.priority
      when 'urgent'::public.duty_priority then 'critical'::public.notification_severity
      when 'high'::public.duty_priority then 'warning'::public.notification_severity
      else 'info'::public.notification_severity
    end,
    'New duty assigned: ' || duty_row.title,
    operation_row.title || ' · ' || start_text || ' · ' || location_text,
    '/volunteer',
    source,
    new.assigned_by
  );

  return new;
end;
$$;

create or replace function app_private.generate_due_duty_reminders_impl(
  p_horizon_hours integer default 24
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  safe_hours integer := greatest(1, least(coalesce(p_horizon_hours, 24), 168));
  row_data record;
  generated integer := 0;
  source text;
begin
  if actor is null then raise exception 'Authentication required'; end if;
  if not app_private.can_view_command_center(actor) then raise exception 'Command center access required'; end if;

  for row_data in
    select
      da.id as assignment_id,
      da.assigned_by,
      vp.user_id,
      od.id as duty_id,
      od.title as duty_title,
      od.priority,
      od.org_unit_id,
      od.operation_id,
      o.title as operation_title,
      coalesce(od.starts_at, os.starts_at, o.starts_at) as starts_at,
      coalesce(nullif(trim(od.location), ''), nullif(trim(os.location), ''), nullif(trim(o.location), ''), 'Location to be confirmed') as location
    from public.duty_assignments da
    join public.operation_duties od on od.id = da.duty_id and od.is_active
    join public.operations o on o.id = od.operation_id
    join public.volunteer_profiles vp on vp.id = da.volunteer_id and vp.is_active
    left join public.operation_shifts os on os.id = od.shift_id and os.is_active
    where da.status in ('assigned'::public.duty_status, 'accepted'::public.duty_status)
      and coalesce(od.starts_at, os.starts_at, o.starts_at) is not null
      and coalesce(od.starts_at, os.starts_at, o.starts_at) >= now()
      and coalesce(od.starts_at, os.starts_at, o.starts_at) <= now() + make_interval(hours => safe_hours)
      and app_private.can_manage_operation(actor, od.operation_id)
    order by coalesce(od.starts_at, os.starts_at, o.starts_at)
  loop
    source := 'duty-due:' || row_data.assignment_id::text || ':' || floor(extract(epoch from row_data.starts_at))::bigint::text;

    if not exists (select 1 from public.notification_messages m where m.source_key = source) then
      perform app_private.publish_direct_notification_to_user(
        row_data.user_id,
        row_data.org_unit_id,
        row_data.operation_id,
        'duty_reminder'::public.notification_kind,
        case row_data.priority
          when 'urgent'::public.duty_priority then 'critical'::public.notification_severity
          when 'high'::public.duty_priority then 'warning'::public.notification_severity
          else 'warning'::public.notification_severity
        end,
        'Duty reminder: ' || row_data.duty_title,
        row_data.operation_title || ' starts ' || to_char(row_data.starts_at, 'DD Mon YYYY HH24:MI TZ') || ' · ' || row_data.location,
        '/volunteer',
        source,
        actor
      );
      generated := generated + 1;
    end if;
  end loop;

  if generated > 0 then
    insert into public.audit_events(actor_id, action, entity_type, entity_id, org_unit_id, detail)
    values(actor, 'duty_reminders_generated', 'notification_batch', null, null,
      jsonb_build_object('generated_count', generated, 'horizon_hours', safe_hours));
  end if;

  return generated;
end;
$$;

create or replace function app_private.notify_operation_status_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  next_id uuid := gen_random_uuid();
  next_no text := 'PTI-NOT-' || to_char(now(), 'YYYYMMDD') || '-' || upper(substr(replace(next_id::text, '-', ''), 1, 8));
  source text;
  recipient_total integer;
begin
  if old.status is not distinct from new.status then return new; end if;
  if new.status = 'draft'::public.operation_status then return new; end if;

  source := 'operation-status:' || new.id::text || ':' || new.status::text || ':' || floor(extract(epoch from now()))::bigint::text;

  insert into public.notification_messages(
    id, notification_no, kind, severity, status, title, body, audience,
    org_unit_id, operation_id, target_spec, action_url, source_key,
    published_at, created_by
  )
  values(
    next_id,
    next_no,
    'operation_update',
    case new.status
      when 'cancelled'::public.operation_status then 'critical'::public.notification_severity
      when 'active'::public.operation_status then 'success'::public.notification_severity
      when 'completed'::public.operation_status then 'success'::public.notification_severity
      else 'info'::public.notification_severity
    end,
    'published',
    'Operation update: ' || new.title,
    'Status changed to ' || upper(replace(new.status::text, '_', ' ')) || '.',
    'operation_participants',
    new.org_unit_id,
    new.id,
    '{}'::jsonb,
    '/volunteer',
    source,
    now(),
    auth.uid()
  )
  on conflict (source_key) do nothing;

  if not found then return new; end if;

  insert into public.notification_deliveries(message_id, recipient_user_id)
  select next_id, recipients.user_id
  from app_private.notification_recipient_ids(
    'operation_participants'::public.notification_audience,
    new.org_unit_id,
    new.id,
    '{}'::jsonb
  ) recipients
  on conflict (message_id, recipient_user_id) do nothing;

  get diagnostics recipient_total = row_count;

  if recipient_total = 0 then
    delete from public.notification_messages where id = next_id;
  end if;

  return new;
end;
$$;

