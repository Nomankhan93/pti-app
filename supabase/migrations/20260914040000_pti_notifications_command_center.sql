create or replace function app_private.can_view_command_center(
  p_user_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    app_private.is_legacy_admin(p_user_id)
    or exists (
      select 1
      from public.organization_role_assignments ra
      where ra.user_id = p_user_id
        and ra.is_active
        and ra.role in (
          'super_admin'::public.organization_role,
          'central_leadership'::public.organization_role,
          'national_operations_admin'::public.organization_role,
          'national_finance_admin'::public.organization_role,
          'provincial_coordinator'::public.organization_role,
          'divisional_coordinator'::public.organization_role,
          'district_coordinator'::public.organization_role,
          'tehsil_coordinator'::public.organization_role,
          'supervisor'::public.organization_role,
          'auditor'::public.organization_role
        )
    )
    or exists (
      select 1
      from public.operation_coordinators oc
      where oc.user_id = p_user_id
        and oc.is_active
    );
$$;

create or replace function app_private.can_manage_notifications(
  p_user_id uuid,
  p_target_org_unit uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    app_private.is_legacy_admin(p_user_id)
    or exists (
      select 1
      from public.organization_role_assignments ra
      join public.organization_units scope_unit on scope_unit.id = ra.org_unit_id
      where ra.user_id = p_user_id
        and ra.is_active
        and scope_unit.is_active
        and ra.role in (
          'super_admin'::public.organization_role,
          'central_leadership'::public.organization_role,
          'national_operations_admin'::public.organization_role,
          'provincial_coordinator'::public.organization_role,
          'divisional_coordinator'::public.organization_role,
          'district_coordinator'::public.organization_role,
          'tehsil_coordinator'::public.organization_role,
          'supervisor'::public.organization_role
        )
        and app_private.is_org_descendant(p_target_org_unit, ra.org_unit_id)
    );
$$;

create or replace function app_private.user_in_notification_scope(
  p_user_id uuid,
  p_org_unit_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.members m
    where m.user_id = p_user_id
      and m.is_active
      and m.org_unit_id is not null
      and app_private.is_org_descendant(m.org_unit_id, p_org_unit_id)
  )
  or exists (
    select 1
    from public.volunteer_profiles vp
    where vp.user_id = p_user_id
      and vp.is_active
      and app_private.is_org_descendant(vp.org_unit_id, p_org_unit_id)
  )
  or exists (
    select 1
    from public.organization_role_assignments ra
    where ra.user_id = p_user_id
      and ra.is_active
      and app_private.is_org_descendant(ra.org_unit_id, p_org_unit_id)
  )
  or exists (
    select 1
    from public.finance_role_assignments fra
    where fra.user_id = p_user_id
      and fra.is_active
      and app_private.is_org_descendant(fra.org_unit_id, p_org_unit_id)
  );
$$;

