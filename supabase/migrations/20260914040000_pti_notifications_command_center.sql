-- PTI Digital Operations Platform — Phase 7
-- Notifications & Operational Command Center
-- Targeted announcements, alerts, duty reminders and operational updates.
-- Depends on Phase 1–6 migrations.

begin;

-- -----------------------------------------------------------------------------
-- Types
-- -----------------------------------------------------------------------------

create type public.notification_kind as enum (
  'announcement',
  'alert',
  'duty_reminder',
  'operation_update'
);

create type public.notification_severity as enum (
  'info',
  'success',
  'warning',
  'critical'
);

create type public.notification_audience as enum (
  'org_scope',
  'members',
  'volunteers',
  'organization_roles',
  'finance_roles',
  'operation_participants',
  'specific_users'
);

create type public.notification_status as enum (
  'published',
  'cancelled'
);

-- -----------------------------------------------------------------------------
-- Core notification ledger
-- -----------------------------------------------------------------------------

create table public.notification_messages (
  id uuid primary key default gen_random_uuid(),
  notification_no text not null unique,
  kind public.notification_kind not null,
  severity public.notification_severity not null default 'info',
  status public.notification_status not null default 'published',
  title text not null,
  body text not null,
  audience public.notification_audience not null,
  org_unit_id uuid not null references public.organization_units(id) on delete restrict,
  operation_id uuid references public.operations(id) on delete set null,
  target_spec jsonb not null default '{}'::jsonb,
  action_url text,
  source_key text unique,
  published_at timestamptz not null default now(),
  expires_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  cancelled_at timestamptz,
  cancelled_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint notification_messages_title_check check (length(trim(title)) between 2 and 160),
  constraint notification_messages_body_check check (length(trim(body)) between 2 and 4000),
  constraint notification_messages_action_url_check check (
    action_url is null
    or (
      length(action_url) <= 500
      and (action_url like '/%' or action_url like 'https://%')
    )
  ),
  constraint notification_messages_target_spec_check check (jsonb_typeof(target_spec) = 'object'),
  constraint notification_messages_expiry_check check (expires_at is null or expires_at > published_at),
  constraint notification_messages_cancel_state_check check (
    (status = 'published'::public.notification_status and cancelled_at is null and cancelled_by is null)
    or (status = 'cancelled'::public.notification_status and cancelled_at is not null)
  )
);

create table public.notification_deliveries (
  id bigint generated by default as identity primary key,
  message_id uuid not null references public.notification_messages(id) on delete cascade,
  recipient_user_id uuid not null references auth.users(id) on delete cascade,
  delivered_at timestamptz not null default now(),
  read_at timestamptz,
  archived_at timestamptz,
  unique (message_id, recipient_user_id),
  constraint notification_deliveries_archive_check check (archived_at is null or archived_at >= delivered_at),
  constraint notification_deliveries_read_check check (read_at is null or read_at >= delivered_at)
);

create index notification_messages_scope_idx
  on public.notification_messages(org_unit_id, published_at desc);
create index notification_messages_operation_idx
  on public.notification_messages(operation_id, published_at desc)
  where operation_id is not null;
create index notification_messages_active_idx
  on public.notification_messages(status, published_at desc, expires_at);
create index notification_messages_created_by_idx
  on public.notification_messages(created_by)
  where created_by is not null;
create index notification_messages_cancelled_by_idx
  on public.notification_messages(cancelled_by)
  where cancelled_by is not null;
create index notification_deliveries_recipient_idx
  on public.notification_deliveries(recipient_user_id, archived_at, read_at, delivered_at desc);
create index notification_deliveries_message_idx
  on public.notification_deliveries(message_id, delivered_at desc);

