create or replace function app_private.my_command_center_access_impl()
returns table(
  can_view boolean,
  can_manage boolean,
  default_org_unit_id uuid,
  default_org_unit_name text,
  default_org_unit_level public.organization_level
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  default_scope public.organization_units;
begin
  if actor is null then
    return query select false, false, null::uuid, null::text, null::public.organization_level;
    return;
  end if;

  if app_private.is_legacy_admin(actor) then
    select * into default_scope
    from public.organization_units ou
    where ou.level = 'central'::public.organization_level
      and ou.is_active
    order by ou.created_at
    limit 1;
  else
    select ou.* into default_scope
    from public.organization_role_assignments ra
    join public.organization_units ou on ou.id = ra.org_unit_id
    where ra.user_id = actor
      and ra.is_active
      and ou.is_active
      and ra.role in (
        'super_admin'::public.organization_role,
        'central_leadership'::public.organization_role,
        'national_operations_admin'::public.organization_role,
        'national_finance_admin'::public.organization_role,
        'provincial_coordinator'::public.organization_role,
        'divisional_coordinator'::public.organization_role,
        'district_coordinator'::public.organization_role,
        'tehsil_coordinator'::public.organization_role,
        'supervisor'::public.organization_role,
        'auditor'::public.organization_role
      )
    order by case ou.level
      when 'central'::public.organization_level then 0
      when 'province'::public.organization_level then 1
      when 'division'::public.organization_level then 2
      when 'district'::public.organization_level then 3
      when 'tehsil'::public.organization_level then 4
      else 9 end,
      ou.name
    limit 1;

    if default_scope.id is null then
      select ou.* into default_scope
      from public.operation_coordinators oc
      join public.operations o on o.id = oc.operation_id
      join public.organization_units ou on ou.id = o.org_unit_id
      where oc.user_id = actor
        and oc.is_active
        and ou.is_active
      order by o.created_at desc
      limit 1;
    end if;
  end if;

  return query
  select
    app_private.can_view_command_center(actor),
    (
      app_private.is_legacy_admin(actor)
      or exists (
        select 1
        from public.organization_role_assignments ra
        where ra.user_id = actor
          and ra.is_active
          and ra.role in (
            'super_admin'::public.organization_role,
            'central_leadership'::public.organization_role,
            'national_operations_admin'::public.organization_role,
            'provincial_coordinator'::public.organization_role,
            'divisional_coordinator'::public.organization_role,
            'district_coordinator'::public.organization_role,
            'tehsil_coordinator'::public.organization_role,
            'supervisor'::public.organization_role
          )
      )
      or exists (
        select 1 from public.operation_coordinators oc
        where oc.user_id = actor and oc.is_active
      )
    ),
    default_scope.id,
    default_scope.name,
    default_scope.level;
end;
$$;

create or replace function app_private.list_notification_scopes_impl()
returns table(
  id uuid,
  parent_id uuid,
  level public.organization_level,
  name text,
  code text
)
language sql
stable
security definer
set search_path = ''
as $$
  select ou.id, ou.parent_id, ou.level, ou.name, ou.code
  from public.organization_units ou
  where ou.is_active
    and (
      app_private.can_access_org_unit(auth.uid(), ou.id)
      or exists (
        select 1
        from public.operation_coordinators oc
        join public.operations o on o.id = oc.operation_id
        where oc.user_id = auth.uid()
          and oc.is_active
          and o.org_unit_id = ou.id
      )
    )
  order by
    case ou.level
      when 'central'::public.organization_level then 0
      when 'province'::public.organization_level then 1
      when 'division'::public.organization_level then 2
      when 'district'::public.organization_level then 3
      when 'tehsil'::public.organization_level then 4
      else 9 end,
    ou.name;
$$;

