create or replace function app_private.list_command_center_messages_impl(
  p_org_unit_id uuid default null,
  p_limit integer default 50
)
returns table(
  id uuid,
  notification_no text,
  kind public.notification_kind,
  severity public.notification_severity,
  status public.notification_status,
  title text,
  body text,
  audience public.notification_audience,
  org_unit_id uuid,
  org_unit_name text,
  operation_id uuid,
  operation_title text,
  action_url text,
  published_at timestamptz,
  expires_at timestamptz,
  created_by uuid,
  recipient_count bigint,
  read_count bigint,
  unread_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  safe_limit integer := greatest(1, least(coalesce(p_limit, 50), 100));
begin
  if actor is null or not app_private.can_view_command_center(actor) then
    raise exception 'Command center access required';
  end if;

  return query
  select
    m.id,
    m.notification_no,
    m.kind,
    m.severity,
    m.status,
    m.title,
    m.body,
    m.audience,
    m.org_unit_id,
    ou.name,
    m.operation_id,
    o.title,
    m.action_url,
    m.published_at,
    m.expires_at,
    m.created_by,
    count(d.id)::bigint,
    count(d.id) filter (where d.read_at is not null)::bigint,
    count(d.id) filter (where d.read_at is null and d.archived_at is null)::bigint
  from public.notification_messages m
  join public.organization_units ou on ou.id = m.org_unit_id
  left join public.operations o on o.id = m.operation_id
  left join public.notification_deliveries d on d.message_id = m.id
  where (
      app_private.can_manage_notifications(actor, m.org_unit_id)
      or (m.operation_id is not null and app_private.can_manage_operation(actor, m.operation_id))
      or app_private.can_access_org_unit(actor, m.org_unit_id)
    )
    and (
      p_org_unit_id is null
      or app_private.is_org_descendant(m.org_unit_id, p_org_unit_id)
    )
  group by m.id, ou.name, o.title
  order by m.published_at desc
  limit safe_limit;
end;
$$;

create or replace function app_private.publish_notification_impl(
  p_org_unit_id uuid,
  p_kind public.notification_kind,
  p_severity public.notification_severity,
  p_title text,
  p_body text,
  p_audience public.notification_audience,
  p_operation_id uuid default null,
  p_action_url text default null,
  p_expires_at timestamptz default null,
  p_target_spec jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  clean_title text := trim(coalesce(p_title, ''));
  clean_body text := trim(coalesce(p_body, ''));
  clean_action text := nullif(trim(coalesce(p_action_url, '')), '');
  next_id uuid := gen_random_uuid();
  next_no text := 'PTI-NOT-' || to_char(now(), 'YYYYMMDD') || '-' || upper(substr(replace(next_id::text, '-', ''), 1, 8));
  recipient_total integer := 0;
  operation_row public.operations;
begin
  if actor is null then raise exception 'Authentication required'; end if;
  if p_org_unit_id is null then raise exception 'Organization scope is required'; end if;
  if length(clean_title) < 2 or length(clean_title) > 160 then raise exception 'Notification title must be 2–160 characters'; end if;
  if length(clean_body) < 2 or length(clean_body) > 4000 then raise exception 'Notification body must be 2–4000 characters'; end if;
  if p_expires_at is not null and p_expires_at <= now() then raise exception 'Expiry must be in the future'; end if;
  if clean_action is not null and clean_action not like '/%' and clean_action not like 'https://%' then raise exception 'Action URL must be a relative path or HTTPS URL'; end if;
  if jsonb_typeof(coalesce(p_target_spec, '{}'::jsonb)) <> 'object' then raise exception 'Target specification must be a JSON object'; end if;

  if p_operation_id is not null then
    select * into operation_row from public.operations where id = p_operation_id;
    if not found then raise exception 'Operation not found'; end if;
    if not app_private.is_org_descendant(operation_row.org_unit_id, p_org_unit_id) then
      raise exception 'Operation is outside the selected notification scope';
    end if;
  end if;

  if p_audience = 'operation_participants'::public.notification_audience
     or p_kind = 'operation_update'::public.notification_kind then
    if p_operation_id is null then raise exception 'Operation notifications require an operation'; end if;
    if not app_private.can_manage_operation(actor, p_operation_id) then raise exception 'Operation notification access required'; end if;
  elsif not app_private.can_manage_notifications(actor, p_org_unit_id) then
    raise exception 'Notification publishing access required';
  end if;

  if p_audience = 'organization_roles'::public.notification_audience
     and jsonb_array_length(coalesce(p_target_spec->'organization_roles', '[]'::jsonb)) = 0 then
    raise exception 'Choose at least one organization role';
  end if;

  if p_audience = 'finance_roles'::public.notification_audience
     and jsonb_array_length(coalesce(p_target_spec->'finance_roles', '[]'::jsonb)) = 0 then
    raise exception 'Choose at least one finance role';
  end if;

  if p_audience = 'specific_users'::public.notification_audience
     and jsonb_array_length(coalesce(p_target_spec->'user_ids', '[]'::jsonb)) = 0 then
    raise exception 'Choose at least one target user';
  end if;

  insert into public.notification_messages(
    id, notification_no, kind, severity, status, title, body, audience,
    org_unit_id, operation_id, target_spec, action_url, published_at,
    expires_at, created_by
  )
  values(
    next_id, next_no, p_kind, p_severity, 'published', clean_title, clean_body,
    p_audience, p_org_unit_id, p_operation_id, coalesce(p_target_spec, '{}'::jsonb),
    clean_action, now(), p_expires_at, actor
  );

  insert into public.notification_deliveries(message_id, recipient_user_id)
  select next_id, recipients.user_id
  from app_private.notification_recipient_ids(
    p_audience,
    p_org_unit_id,
    p_operation_id,
    coalesce(p_target_spec, '{}'::jsonb)
  ) recipients
  on conflict (message_id, recipient_user_id) do nothing;

  get diagnostics recipient_total = row_count;

  if recipient_total = 0 then
    raise exception 'No eligible recipients were found for this notification target';
  end if;

  insert into public.audit_events(actor_id, action, entity_type, entity_id, org_unit_id, detail)
  values(
    actor,
    'notification_published',
    'notification_message',
    next_id,
    p_org_unit_id,
    jsonb_build_object(
      'notification_no', next_no,
      'kind', p_kind,
      'severity', p_severity,
      'audience', p_audience,
      'operation_id', p_operation_id,
      'recipient_count', recipient_total
    )
  );

  return jsonb_build_object(
    'message_id', next_id,
    'notification_no', next_no,
    'recipient_count', recipient_total
  );
end;
$$;

create or replace function app_private.cancel_notification_impl(
  p_message_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  row_data public.notification_messages;
begin
  if actor is null then raise exception 'Authentication required'; end if;

  select * into row_data
  from public.notification_messages
  where id = p_message_id
  for update;

  if not found then raise exception 'Notification not found'; end if;

  if not (
    app_private.can_manage_notifications(actor, row_data.org_unit_id)
    or (row_data.operation_id is not null and app_private.can_manage_operation(actor, row_data.operation_id))
  ) then
    raise exception 'Notification cancellation access required';
  end if;

  if row_data.status = 'cancelled'::public.notification_status then return; end if;

  update public.notification_messages
  set status = 'cancelled',
      cancelled_at = now(),
      cancelled_by = actor
  where id = row_data.id;

  insert into public.audit_events(actor_id, action, entity_type, entity_id, org_unit_id, detail)
  values(actor, 'notification_cancelled', 'notification_message', row_data.id, row_data.org_unit_id,
    jsonb_build_object('notification_no', row_data.notification_no));
end;
$$;

