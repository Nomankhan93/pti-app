language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  safe_limit integer := greatest(1, least(coalesce(p_limit, 50), 100));
begin
  return query
  select
    d.id,
    m.id,
    m.notification_no,
    m.kind,
    m.severity,
    m.title,
    m.body,
    m.action_url,
    m.operation_id,
    m.org_unit_id,
