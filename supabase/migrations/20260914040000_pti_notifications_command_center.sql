create policy notification_messages_select_command_center
on public.notification_messages
for select
to authenticated
using (
  app_private.can_view_command_center((select auth.uid()))
  and (
    app_private.can_manage_notifications((select auth.uid()), org_unit_id)
    or (operation_id is not null and app_private.can_manage_operation((select auth.uid()), operation_id))
    or app_private.can_access_org_unit((select auth.uid()), org_unit_id)
  )
);

create policy notification_deliveries_select_own
on public.notification_deliveries
for select
to authenticated
using (recipient_user_id = (select auth.uid()));

revoke all on public.notification_messages from public, anon, authenticated;
revoke all on public.notification_deliveries from public, anon, authenticated;

