create or replace function app_private.list_my_notifications_impl(
  p_limit integer default 50,
  p_before timestamptz default null
)
returns table(
  delivery_id bigint,
  message_id uuid,
  notification_no text,
  kind public.notification_kind,
  severity public.notification_severity,
  title text,
  body text,
  action_url text,
  operation_id uuid,
  org_unit_id uuid,
  org_unit_name text,
  published_at timestamptz,
